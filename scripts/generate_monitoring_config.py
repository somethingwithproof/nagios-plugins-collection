"""Generate Icinga 2 CheckCommands, Nagios commands and man pages from the plugin parsers.

Each installed command's argparse parser is the single source of its options,
so the monitoring definitions cannot drift from ``--help``. Run without
arguments to rewrite ``contrib/``; ``--check`` exits 1 when a file is stale.

Secrets are never passed on the command line: the Icinga 2 commands map them to
the plugin's environment variables, and both formats expose the ``-file``
options.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import os
import sys
import tomllib
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRIB = ROOT / "contrib"
ICINGA = CONTRIB / "icinga2/nagios-plugins-collection.conf"
NAGIOS = CONTRIB / "nagios/nagios-plugins-collection.cfg"
MAN = CONTRIB / "man/man1"
#: Where the Debian and RPM packages install the commands.
PLUGIN_DIR = "/usr/lib/nagios/plugins"
PROJECT = "nagios-plugins-collection"
HOMEPAGE = "https://github.com/somethingwithproof/nagios-plugins-collection"
#: Options that only make sense interactively.
SKIPPED = {"help", "verbose"}
HEADER = "SPDX-FileCopyrightText: 2026 Thomas Vincent", "SPDX-License-Identifier: Apache-2.0"
NOTICE = "Generated by scripts/generate_monitoring_config.py; do not edit."


@dataclass(frozen=True)
class Option:
    """One command-line option as the generated definitions need it."""

    flag: str
    flags: tuple[str, ...]
    dest: str
    metavar: str | None
    help: str
    required: bool
    repeat: bool
    choices: tuple[str, ...]

    @property
    def takes_value(self) -> bool:
        """Whether the option is followed by a value (rather than a switch)."""
        return self.metavar is not None


@dataclass(frozen=True)
class Secret:
    """A credential the plugin also reads from the environment."""

    dest: str
    flag: str
    env: str
    file_env: str
    required: bool


@dataclass(frozen=True)
class Command:
    """An installed command, its options and secrets."""

    name: str
    summary: str
    options: tuple[Option, ...]
    secrets: tuple[Secret, ...]


def _plugin(module_name: str) -> type:
    from nagios_plugins.base import NagiosPlugin

    module = importlib.import_module(module_name)
    (plugin,) = (
        value
        for value in vars(module).values()
        if inspect.isclass(value)
        and issubclass(value, NagiosPlugin)
        and value.__module__ == module.__name__
    )
    return plugin


def _help(parser: argparse.ArgumentParser, action: argparse.Action) -> str:
    """Return the option's help with ``%(default)s`` and friends expanded, on one line."""
    if not action.help:
        return ""
    params = {**vars(action), "prog": parser.prog}
    params = {key: getattr(value, "__name__", value) for key, value in params.items()}
    if params.get("choices") is not None:
        params["choices"] = ", ".join(map(str, params["choices"]))
    return " ".join((action.help % params).split())


def _metavar(action: argparse.Action) -> str | None:
    if action.nargs == 0:
        return None
    metavar = action.metavar or action.dest.upper()
    return metavar if isinstance(metavar, str) else " ".join(metavar)


def load_commands() -> list[Command]:
    """Build every ``[project.scripts]`` command's parser and describe its options."""
    scripts = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["scripts"]
    commands = []
    for name, reference in sorted(scripts.items()):
        plugin = _plugin(reference.partition(":")[0])()
        parser = plugin.parser
        secrets = tuple(
            Secret(secret.dest, secret.flag, secret.env, secret.file_env, secret.required)
            for secret in parser.secret_options
        )
        hidden = {secret.dest for secret in secrets}
        options = []
        for action in parser._actions:  # argparse exposes no public option list
            if (
                not action.option_strings
                or action.dest in SKIPPED | hidden
                or action.help == argparse.SUPPRESS
            ):
                continue
            options.append(
                Option(
                    flag=max(action.option_strings, key=len),
                    flags=tuple(action.option_strings),
                    dest=action.dest,
                    metavar=_metavar(action),
                    help=_help(parser, action),
                    required=action.required,
                    repeat=isinstance(action, argparse._AppendAction),
                    choices=tuple(map(str, action.choices or ())),
                )
            )
        summary = (parser.description or name).strip().splitlines()[0]
        commands.append(Command(name, summary, tuple(options), secrets))
    return commands


# Icinga 2 ---------------------------------------------------------------------


def _icinga_string(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$")
    return f'"{escaped}"'


def _icinga_argument(command: Command, option: Option) -> list[str]:
    """Render one ``arguments`` entry: value or switch, repetition, help, requirement."""
    var = f"${command.name}_{option.dest}$"
    lines = [
        f'    "{option.flag}" = {{',
        f'      {"value" if option.takes_value else "set_if"} = "{var}"',
    ]
    if option.repeat:
        lines.append("      repeat_key = true")
    if option.help:
        lines.append(f"      description = {_icinga_string(option.help)}")
    if option.required:
        lines.append("      required = true")
    return [*lines, "    }"]


def _icinga_command(command: Command) -> list[str]:
    """Render one CheckCommand; secrets go into ``env``, never into ``arguments``."""
    lines = [
        "",
        f'object CheckCommand "{command.name}" {{',
        f'  import "{PROJECT}"',
        f'  command = [ "$nagios_plugins_collection_dir$/{command.name}" ]',
        "  arguments = {",
    ]
    for option in command.options:
        lines += _icinga_argument(command, option)
    lines.append("  }")
    if command.secrets:
        lines.append("  env = {")
        lines += [f'    {s.env} = "${command.name}_{s.dest}$"' for s in command.secrets]
        lines.append("  }")
    return [*lines, "}"]


def render_icinga(commands: list[Command]) -> str:
    """Render one CheckCommand per command, importing a template that sets the path."""
    lines = [f"// {line}" for line in (*HEADER, NOTICE)]
    lines += [
        "//",
        "// Include this file from icinga2.conf, then set the custom variables on a",
        "// Service, for example vars.check_website_status_url. Secrets are passed",
        "// through the plugin's environment variables, never on the command line.",
        "",
        f'template CheckCommand "{PROJECT}" {{',
        f'  vars.nagios_plugins_collection_dir = "{PLUGIN_DIR}"',
        "}",
    ]
    for command in commands:
        lines += _icinga_command(command)
    return "\n".join(lines) + "\n"


# Nagios -----------------------------------------------------------------------


def render_nagios(commands: list[Command]) -> str:
    """Render one command per plugin: required options as $ARGn$, then free arguments."""
    lines = [f"# {line}" for line in (*HEADER, NOTICE)]
    lines += [
        "#",
        f"# Paths match the Debian and RPM packages ({PLUGIN_DIR}). Each command takes",
        "# its required options as $ARG1$, $ARG2$, ... in the order listed, and any",
        "# further options (thresholds, TLS, -file secrets) in the last $ARGn$. Pass",
        "# secrets with the -file options or the CHECK_* environment variables, not as",
        "# plain values.",
    ]
    for command in commands:
        required = [option for option in command.options if option.required]
        required_secrets = [secret for secret in command.secrets if secret.required]
        parts = [f"{PLUGIN_DIR}/{command.name}"]
        notes = []
        for number, option in enumerate(required, 1):
            parts.append(f"{option.flag} '$ARG{number}$'")
            notes.append(f"#   $ARG{number}$  {option.flag} {option.metavar}")
        extra = len(required) + 1
        parts.append(f"$ARG{extra}$")
        notes.append(f"#   $ARG{extra}$  further options, for example -w/-c")
        for secret in required_secrets:
            notes.append(
                f"#   requires {secret.env} or {secret.file_env} in the environment, "
                f"or {secret.flag}-file in $ARG{extra}$"
            )
        lines += [
            "",
            f"# {command.name}: {command.summary}",
            *notes,
            "define command {",
            f"    command_name    {command.name}",
            f"    command_line    {' '.join(parts)}",
            "}",
        ]
    return "\n".join(lines) + "\n"


# Man pages --------------------------------------------------------------------


def _roff(text: str) -> str:
    """Escape text for a roff line: backslashes, hyphens and leading control characters."""
    text = text.replace("\\", "\\e").replace("-", "\\-")
    return "\\&" + text if text.startswith((".", "'")) else text


def _synopsis(option: Option, flags: tuple[str, ...] | None = None) -> str:
    item = ", ".join(f"\\fB{_roff(flag)}\\fR" for flag in flags or (option.flag,))
    if option.takes_value:
        item += f" \\fI{_roff(option.metavar or '')}\\fR"
    return item if option.required or flags else f"[{item}]"


def render_man(command: Command) -> str:
    """Render a man(7) page: options, environment and the Nagios exit statuses."""
    title = command.name.upper().replace("_", "\\_")
    lines = [f'.\\" {line}' for line in (*HEADER, NOTICE)]
    lines += [
        f'.TH {title} 1 "" "{PROJECT}" "Monitoring Plugins"',
        ".SH NAME",
        f"{_roff(command.name)} \\- {_roff(command.summary)}",
        ".SH SYNOPSIS",
        f".B {_roff(command.name)}",
        " ".join(_synopsis(option) for option in command.options),
        ".SH DESCRIPTION",
        f"\\fB{_roff(command.name)}\\fR prints one status line, with performance data after a",
        "\\(lq|\\(rq, and exits with the Nagios plugin status.",
        ".SH OPTIONS",
        ".TP",
        "\\fB\\-h\\fR, \\fB\\-\\-help\\fR",
        "Show the options and exit.",
        ".TP",
        "\\fB\\-v\\fR, \\fB\\-\\-verbose\\fR",
        "Log more detail to standard error; repeat for debug output.",
    ]
    for option in command.options:
        lines += [".TP", _synopsis(option, option.flags)]
        details = option.help or "See the plugin documentation."
        if option.choices and "one of" not in details:
            details += f" One of: {', '.join(option.choices)}."
        if option.repeat:
            details += " May be given more than once."
        lines.append(_roff(details))
    if command.secrets:
        lines.append(".SH ENVIRONMENT")
        for secret in command.secrets:
            flag = secret.flag
            lines += [
                ".TP",
                f"\\fB{_roff(secret.env)}\\fR",
                _roff(f"The {flag} value, used when neither {flag} nor {flag}-file is given."),
                ".TP",
                f"\\fB{_roff(secret.file_env)}\\fR",
                _roff(f"A file holding the {flag} value, used after {secret.env}."),
            ]
    lines += [
        ".SH EXIT STATUS",
        ".TP",
        ".B 0",
        "OK",
        ".TP",
        ".B 1",
        "WARNING",
        ".TP",
        ".B 2",
        "CRITICAL",
        ".TP",
        ".B 3",
        "UNKNOWN: also for usage errors, missing data and a run that exceeds",
        "\\fB\\-\\-timeout\\fR.",
        ".SH SEE ALSO",
        _roff(f"{HOMEPAGE}#readme"),
    ]
    return "\n".join(lines) + "\n"


# Driver -----------------------------------------------------------------------


def outputs() -> dict[Path, str]:
    """Return every generated file and its content."""
    # argparse wraps usage and help to the terminal width; pin it for stable output.
    os.environ["COLUMNS"] = "80"
    commands = load_commands()
    files = {ICINGA: render_icinga(commands), NAGIOS: render_nagios(commands)}
    files.update({MAN / f"{command.name}.1": render_man(command) for command in commands})
    return files


def _stale(files: dict[Path, str]) -> Iterator[Path]:
    for path, content in files.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            yield path
    if MAN.is_dir():
        yield from (path for path in MAN.glob("*.1") if path not in files)


def main(argv: list[str] | None = None) -> int:
    """Write the generated files, or with ``--check`` report the stale ones."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a file is out of date")
    arguments = parser.parse_args(argv)
    files = outputs()
    stale = sorted(_stale(files))
    if arguments.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: uv run python scripts/generate_monitoring_config.py", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        if path in files:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(files[path], encoding="utf-8")
        else:
            path.unlink()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
